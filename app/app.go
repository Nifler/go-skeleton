// Package app збирає сервіси каркаса докупи і керує їхнім життєвим циклом.
//
// Це єдине місце, яке знає про всі інші пакети (роутер, а згодом логер, БД,
// кеш, чергу). Застосунок (main.go) імпортує лише app і не збирає залежності
// вручну. Порівняй із Laravel: це щось на кшталт service container,
// але без "магії": усе створюється явно в конструкторі New.
package app

import (
	"log"
	"net/http"

	"github.com/Nifler/go-skeleton/httpserver"
)

// App — зібраний застосунок.
type App struct {
	// Router — ЕКСПОРТОВАНЕ поле (велика літера), щоб main.go міг
	// реєструвати маршрути: a.Router.Get(...). Приватним його робити
	// не варто, бо без доступу до роутера застосунок нічого не обслуговуватиме.
	Router *httpserver.Router

	// addr — адреса, яку слухає сервер. Поле приватне: змінювати її після
	// створення не потрібно, вона задається один раз у New.
	addr string
}

// New створює застосунок і всі його сервіси.
//
// Зараз тут лише роутер. З часом у цій функції з'являтимуться логер, БД,
// кеш тощо, і вони створюватимуться саме тут, у правильному порядку.
// Для main.go сигнатура лишиться простою.
func New(addr string) *App {
	return &App{
		Router: httpserver.NewRouter(),
		addr:   addr,
	}
}

// Run запускає HTTP-сервер і блокує виконання, доки сервер не зупиниться.
//
// Повертаємо error, а не викликаємо log.Fatal всередині: рішення, що робити
// з помилкою (завершити програму, повторити спробу), приймає той, хто
// викликає Run. Бібліотечний код не повинен сам завершувати програму.
//
// Згодом тут з'явиться graceful shutdown: Run(ctx) зупинятиме сервер,
// дочекавшись поточних запитів.
func (a *App) Run() error {
	log.Println("listening on", a.addr)

	// a.Router має метод ServeHTTP, тобто неявно є http.Handler.
	return http.ListenAndServe(a.addr, a.Router)
}
